CREATE TABLE shipping (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  public_id UUID NOT NULL UNIQUE,
  order_id BIGINT NOT NULL UNIQUE,
  cost NUMERIC(38, 2) NOT NULL,
  address VARCHAR(255) NOT NULL,
  method VARCHAR(255) NOT NULL CHECK (method IN ('DELIVERY', 'PICKUP')),
  recipient VARCHAR(255) NOT NULL,
  status VARCHAR(255) NOT NULL CHECK (status IN ('PROCESSING', 'SHIPPED', 'OUT_FOR_DELIVERY', 'READY_FOR_PICKUP', 'DELIVERED', 'FAILED', 'RETURNED')),
  tracking_number VARCHAR(255),
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  shipped_at TIMESTAMP(6),
  delivered_at TIMESTAMP(6),
  CONSTRAINT pk_shipping PRIMARY KEY (id)
);

